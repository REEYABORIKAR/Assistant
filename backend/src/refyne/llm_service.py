def _synthesize_clean_title(raw_text: str, default_prefix: str = "Requirement") -> str:
    """Extract or synthesize a clean, short requirement title from raw text without mid-word character slicing."""
    if not raw_text:
        return default_prefix
    
    clean = raw_text.strip()
    clean = re.sub(r'^(?:\d+[\.\)]|[-*•]|REQ[-_]?\d*|BR[-_]?\d*|FR[-_]?\d*)\s*', '', clean, flags=re.IGNORECASE).strip()
    
    if re.search(r'^(prepared by|author|version|date|page|document|table of contents)', clean, flags=re.IGNORECASE):
        return default_prefix

    if len(clean) <= 60:
        return clean.strip(' :-.,;')

    first_clause = re.split(r'[.:;—\n]', clean)[0].strip()
    if 10 <= len(first_clause) <= 70 and not re.search(r'^(prepared by|author|version|date|page)', first_clause, flags=re.IGNORECASE):
        return first_clause.strip(' :-.,;')

    words = clean.split()
    title_words = []
    curr_len = 0
    for w in words:
        if curr_len + len(w) + 1 > 60:
            break
        title_words.append(w)
        curr_len += len(w) + 1

    res = " ".join(title_words).strip(' :-.,;')
    return res if len(res) >= 5 else default_prefix


