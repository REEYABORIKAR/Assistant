VERIFIER_SYSTEM_PROMPT = f"""{SECURITY_GUARDRAIL}

You are a Fact-Checking Auditor. You will receive a source document excerpt and a numbered list of claims that were generated from it (risk factors, missing sections, RTM rows, or document sections). For EACH claim, evaluate whether the source text directly supports or implies it, and assign a confidence score from 0 to 100 with a concise one-sentence reason:

- 80–100: The source text directly states or strongly implies this.
- 50–79: The general concept is grounded, but specific details/numbers/standards are extrapolated.
- 0–49: No reasonable basis in the source — likely unsupported or hallucinated.

Return RAW JSON only adhering strictly to this schema:
{{
  "verdicts": [
    {{
      "claim_index": 0,
      "confidence": 85,
      "verdict": "SUPPORTED",
      "reason": "Directly matches source section on patient authentication."
    }}
  ]
}}
Be terse. One short sentence per reason, no repetition of the claim text."""


async def verify_claims_ai(
    doc_excerpt: str,
    claims: list[str],
    api_key: Optional[str] = None,
    tenant_id: Optional[str] = "default"
) -> dict:
    if not claims:
        return {"verdicts": [], "verified_count": 0, "flagged_count": 0, "total_claims": 0}

    numbered = "\n".join(f"{i}: {c}" for i, c in enumerate(claims))
    user_prompt = f"""SOURCE EXCERPT:
{doc_excerpt[:4000] if doc_excerpt else "No raw excerpt provided."}

CLAIMS TO VERIFY:
{numbered}

Verify each numbered claim against the source excerpt above."""

    ai_result = await _call_groq_json(
        system_prompt=VERIFIER_SYSTEM_PROMPT,
        user_prompt=user_prompt,
        api_key=api_key,
        operation="CLAIM_VERIFICATION",
        tenant_id=tenant_id
    )

    if ai_result and isinstance(ai_result, dict) and "verdicts" in ai_result and isinstance(ai_result["verdicts"], list):
        verdicts = ai_result["verdicts"]
        indexed_verdicts = {}
        for v in verdicts:
            idx = v.get("claim_index")
            if idx is not None:
                indexed_verdicts[int(idx)] = v

        final_verdicts = []
        for i, c in enumerate(claims):
            if i in indexed_verdicts:
                v = indexed_verdicts[i]
                conf = int(v.get("confidence", 80))
                verdict_str = "SUPPORTED" if conf >= 60 else "LOW_CONFIDENCE"
                final_verdicts.append({
                    "claim_index": i,
                    "claim": c,
                    "confidence": conf,
                    "verdict": verdict_str,
                    "reason": v.get("reason", "Verified against document context.")
                })
            else:
                # The verifier LLM did not return a verdict for this claim index (e.g. it
                # evaluated fewer claims than were sent). Do not silently mark this as
                # SUPPORTED — that would render a green checkmark for a claim nobody
                # actually checked. Flag it as unconfirmed instead.
                final_verdicts.append({
                    "claim_index": i,
                    "claim": c,
                    "confidence": 50,
                    "verdict": "LOW_CONFIDENCE",
                    "reason": "Not evaluated by verifier — treat as unconfirmed pending re-check."
                })
        
        verified_count = sum(1 for v in final_verdicts if v["confidence"] >= 60)
        flagged_count = sum(1 for v in final_verdicts if v["confidence"] < 60)
        flagged_items = [v for v in final_verdicts if v["confidence"] < 60]

        return {
            "verdicts": final_verdicts,
            "verified_count": verified_count,
            "flagged_count": flagged_count,
            "flagged_items": flagged_items,
            "total_claims": len(claims)
        }

    # Deterministic fallback claim verifier
    lower_doc = (doc_excerpt or "").lower()
    final_verdicts = []
    for i, c in enumerate(claims):
        c_lower = c.lower()
        words = [w for w in re.findall(r'\b\w{3,}\b', c_lower) if w not in ("the", "and", "for", "with", "this", "that", "all", "are", "from")]
        matches = [w for w in words if w in lower_doc]
        overlap_ratio = (len(matches) / max(1, len(words))) if words else 0.0
        
        if overlap_ratio >= 0.15:
            conf = min(95, max(75, int(65 + (overlap_ratio * 30))))
            verdict_str = "SUPPORTED"
            reason = f"Grounding verified: matched {len(matches)} source keywords in document context."
        elif overlap_ratio >= 0.12:
            conf = 65
            verdict_str = "SUPPORTED"
            reason = "General concept is grounded in source context; specific details are extrapolated."
        else:
            conf = 45
            verdict_str = "LOW_CONFIDENCE"
            reason = "Limited direct mention found in source excerpt; flag for stakeholder clarification."

        final_verdicts.append({
            "claim_index": i,
            "claim": c,
            "confidence": conf,
            "verdict": verdict_str,
            "reason": reason
        })

    verified_count = sum(1 for v in final_verdicts if v["confidence"] >= 60)
    flagged_count = sum(1 for v in final_verdicts if v["confidence"] < 60)
    flagged_items = [v for v in final_verdicts if v["confidence"] < 60]

    p_tok = max(len(user_prompt) // 4, 150)
    c_tok = len(claims) * 25
    record_token_usage(tenant_id or "default", "qwen/qwen3.8-27b", "CLAIM_VERIFICATION", p_tok, c_tok, 120, "SIMULATED")

    return {
        "verdicts": final_verdicts,
        "verified_count": verified_count,
        "flagged_count": flagged_count,
        "flagged_items": flagged_items,
        "total_claims": len(claims)
    }


async def generate_document_ai(
    doc_type: str,
    title: str,
    audit_json: dict,
    domain_profile: dict,
    doc_excerpt: str,
    revision_feedback: str | None = None,
    previous_sections: str | None = None,
    previous_doc: dict | None = None,
    api_key: str | None = None,
    tenant_id: str | None = None,
    project_analysis: dict | None = None
) -> dict:
    dtype = (doc_type or "BRD").upper()
    doc_title = title or f"{dtype} Specification"
    
    if not domain_profile:
        domain_profile = detect_domain(doc_excerpt or title)

    # For USER_STORIES: use dedicated requirement-to-backlog transformation engine
    if dtype == "USER_STORIES":
        from refyne.user_story_engine import generate_complete_user_stories_pipeline
        doc_content = generate_complete_user_stories_pipeline(
            doc_text=doc_excerpt or title,
            title=doc_title,
            previous_doc=previous_doc,
            revision_feedback=revision_feedback
        )
        doc_content["_source_audit"] = audit_json or {}
        doc_content["_domain_profile"] = domain_profile or {"domain": "HEALTHCARE"}
        doc_content["_doc_excerpt"] = (doc_excerpt or "")[:4000]
        return doc_content

    user_prompt = build_generation_prompt(
        doc_type=dtype,
        doc_excerpt=doc_excerpt,
        audit_json=audit_json or {},
        domain_profile=domain_profile,
        project_title=doc_title,
        revision_feedback=revision_feedback,
        previous_sections=previous_sections,
        project_analysis=project_analysis
    )

    ai_result = await _call_groq_json(
        system_prompt=DOCUMENT_GENERATION_SYSTEM_PROMPT,
        user_prompt=user_prompt,
        api_key=api_key,
        operation="DOC_GENERATION",
        tenant_id=tenant_id
    )

    if ai_result and isinstance(ai_result, dict) and "sections" in ai_result and isinstance(ai_result["sections"], list) and len(ai_result["sections"]) > 0:
        doc_content = {
            "doc_type": ai_result.get("doc_type", dtype),
            "title": ai_result.get("title", f"{dtype} — {doc_title}"),
            "version": ai_result.get("version", "v1.0"),
            "status": ai_result.get("status", "PENDING_APPROVAL"),
            "revision_history": ai_result.get("revision_history", []),
            "parent_id": ai_result.get("parent_id", None),
            "sections": ai_result["sections"],
            "_source_audit": audit_json,
            "_domain_profile": domain_profile,
            "_doc_excerpt": doc_excerpt[:4000] if doc_excerpt else ""
        }
    else:
        # Fallback to deterministic grounded generator
        fallback_doc = _build_grounded_fallback_document(
            doc_type=dtype,
            title=doc_title,
            audit_json=audit_json or {},
            domain_profile=domain_profile,
            doc_excerpt=doc_excerpt,
            revision_feedback=revision_feedback,
            project_analysis=project_analysis
        )
        fallback_doc["revision_history"] = []
        fallback_doc["parent_id"] = None
        fallback_doc["_source_audit"] = audit_json
        fallback_doc["_domain_profile"] = domain_profile
        fallback_doc["_doc_excerpt"] = doc_excerpt[:4000] if doc_excerpt else ""
        doc_content = fallback_doc

        p_tok = max(len(user_prompt) // 4, 300)
        c_tok = 850
        record_token_usage(tenant_id or "default", "qwen/qwen3.8-27b", "DOC_GENERATION", p_tok, c_tok, 380, "SIMULATED")

    # Call Site B: Batched claim verification on generated document
    gen_claims = []
    for s in doc_content.get("sections", []):
        if "table" in s and isinstance(s["table"], list):
            for row in s["table"][1:6]:
                if isinstance(row, list) and len(row) >= 2:
                    gen_claims.append(f"{row[0]}: {row[1]} — {' '.join(str(x) for x in row[2:4])}")
        elif "body" in s and isinstance(s["body"], str):
            gen_claims.append(f"{s.get('title', 'Section')}: {s['body'][:120]}")

    if gen_claims:
        doc_verification = await verify_claims_ai(
            doc_excerpt=doc_excerpt or doc_title,
            claims=gen_claims[:12],
            api_key=api_key,
            tenant_id=tenant_id
        )
        doc_content["verification_summary"] = doc_verification

    return doc_content


